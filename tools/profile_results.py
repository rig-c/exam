#!/usr/bin/env python3
"""Splice the two canonical --profile outputs and derived counts into an org README.

Only the destination is written; the exam's generators and grading are unchanged.
Marker errors and unrecognised legacy prose fail before any bytes are written.
"""
import argparse
import importlib.util
from pathlib import Path
import re
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]
SUMMARY_START = '<!-- exam-summary:start — generated by rig-c/exam; do not edit by hand -->\n'.encode('utf-8')
SUMMARY_END = b'<!-- exam-summary:end -->'


class ProfileError(ValueError):
    pass


def generator(path):
    spec = importlib.util.spec_from_file_location('profile_' + path.parent.name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def summary(basic, advanced):
    """Use the generators' selection: counted Basic groups; Advanced by_model cells.

    Basic considers every graded task (including the separately tabled painting),
    across all counted sittings. Advanced requires all rounds, uses the selected
    sitting of each round, and never folds a shin-scale what-if into its grade.
    """
    groups = {}
    for run in basic.runs():
        if basic.counted(run):
            groups.setdefault(run['group'], []).append(run)
    passed = 0
    for runs in groups.values():
        tasks = [task for run in runs for task in run['tasks'].values()]
        passed += bool(tasks) and all(t['of'] > 0 and t['passed'] == t['of'] for t in tasks)
    models = advanced.by_model(advanced.sittings())
    complete = [rr for rr in models.values() if all(r in rr for r in advanced.ROUNDS)]

    def all_rows(s):
        grade = s['grade']
        return (grade['of'] > 0 and grade['passed'] == grade['of']
                and all(v == 'PASS' for v in grade['rows'].values()))

    cells = [rr[r] for rr in models.values() for r in advanced.ROUNDS if r in rr]
    all_rounds = sum(all(all_rows(rr[r]) for r in advanced.ROUNDS) for rr in complete)
    failed = sum(not all_rows(s) for s in cells)
    return (
        f'**Basic:** {len(groups)} models, {passed} passed every graded line across their independent '
        f'sittings ({sum(map(len, groups.values()))} sittings). Only tasks actually graded count; '
        'this does not claim that every task was sat.\n\n'
        f'**Advanced:** {len(models)} models, {len(complete)} with all three rounds; {all_rounds} passed '
        f'every graded row in all three. {failed} of {len(cells)} displayed round cells did not pass '
        'every row. Shin-scale what-ifs do not change the recorded grades.\n'
    ).encode('utf-8')


def generated(root=ROOT):
    paths = (root / 'results.py', root / 'advanced/results.py')
    # Keep even the final newline exactly as emitted by each public CLI.
    tables = [subprocess.run([sys.executable, '-B', str(p), '--profile'],
                             check=True, stdout=subprocess.PIPE).stdout for p in paths]
    if any(not t.startswith(b'| model |') or not t.endswith(b'\n') for t in tables):
        raise ProfileError('unexpected --profile output')
    return (*tables, summary(*(generator(p) for p in paths)))


def region(data, name, optional=False):
    """Return (start-of-block, content-start, content-end, end-of-block).

    Count raw marker tokens as well as whole marker lines so malformed, inline,
    duplicate and half-present pairs cannot accidentally be treated as absent.
    """
    token = rb'<!--[ \t]*' + re.escape(name.encode()) + rb':(start|end)\b'
    tokens = list(re.finditer(token, data))
    if optional and not tokens:
        return None
    if [m.group(1) for m in tokens] != [b'start', b'end']:
        raise ProfileError(f'{name}: need exactly one start then one end marker')
    lines = []
    for kind in (b'start', b'end'):
        pattern = (rb'(?m)^[ \t]*<!--[ \t]*' + re.escape(name.encode()) + b':' + kind
                   + rb'\b(?:(?!-->|<!--)[^\r\n])*-->[ \t]*(?:\r?\n|\Z)')
        matches = list(re.finditer(pattern, data))
        if len(matches) != 1:
            raise ProfileError(f'{name}: markers must be complete comments on their own lines')
        lines.append(matches[0])
    start, end = lines
    if not start.group().endswith(b'\n') or start.end() > end.start():
        raise ProfileError(f'{name}: reversed or malformed marker pair')
    return start.start(), start.end(), end.start(), end.end()


# Recognise only the historic count sentences, not the whole paragraph around
# them. The call to sit the exam, Advanced's introduction, links and extra prose
# belong to the profile's editor. Unknown wording needs an explicit migration.
LEGACY_BASIC = re.compile(
    rb'(?:\b(?:[A-Z][a-z]+|[0-9]+) models have sat it, from each vendor\'s lighter tier to its heaviest; '
    rb'(?:[a-z]+|[0-9]+) passed every line, and the (?:[a-z]+|[0-9]+) that missed (?:[a-z]+|[0-9]+) '
    rb'are on the page with the line they missed\.|'
    rb'Every line passed, and the three models named are each their vendor\'s lighter tier\.)'
    rb'[^\S\r\n]*(?=\s*\*\*Sit it with yours:\*\*)'
)
LEGACY_ADVANCED = re.compile(
    rb'\b(?:[A-Z][a-z]+|[0-9]+) models have sat all three rounds and one cell failed; their figures '
    rb'converge in R1 and R3 and spread in R2, where the one new row of edition 0\.21 '
    rb'comes from \(shown here as a what-if\)\.'
)


def splice(data, basic, advanced, counts):
    sections = {name: region(data, name, optional=name == 'exam-summary')
                for name in ('exam', 'exam-advanced', 'exam-summary')}
    present = sorted(r for r in sections.values() if r is not None)
    if any(a[3] > b[0] for a, b in zip(present, present[1:])):
        raise ProfileError('exam marker pairs overlap')
    edits = [(sections[name][1], sections[name][2], value)
             for name, value in (('exam', basic), ('exam-advanced', advanced))]
    if sections['exam-summary'] is not None:
        s = sections['exam-summary']
        edits.append((s[1], s[2], counts))
    else:
        # Legacy counts live between the Basic table and the Advanced table.
        lo, hi = sections['exam'][3], sections['exam-advanced'][0]
        gap = data[lo:hi]
        if lo >= hi:
            raise ProfileError('legacy migration needs Basic before Advanced')
        # Whitespace folding allows the same sentences to be wrapped by an editor.
        # Use a pattern expansion, not normalisation of the surrounding bytes.
        for pattern, label in ((LEGACY_BASIC, 'Basic'), (LEGACY_ADVANCED, 'Advanced')):
            wrapped = re.compile(pattern.pattern.replace(b' ', rb'[ \t\r\n]+'))
            matches = list(wrapped.finditer(gap))
            if len(matches) != 1:
                raise ProfileError(f'legacy {label}: need one recognised count sentence; '
                                   'see .github/README.md for manual migration')
            m = matches[0]
            edits.append((lo + m.start(), lo + m.end(), b''))
        insertion = b'\n' + SUMMARY_START + counts + SUMMARY_END + b'\n'
        edits.append((lo, lo, insertion))
    for start, end, replacement in sorted(edits, reverse=True):
        data = data[:start] + replacement + data[end:]
    return data


def update(path):
    before = path.read_bytes()
    after = splice(before, *generated())
    if before == after:
        return False
    path.write_bytes(after)
    return True


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('readme', type=Path, help='checked-out profile/README.md to update')
    args = parser.parse_args(argv)
    try:
        changed = update(args.readme)
    except (ProfileError, OSError, subprocess.CalledProcessError) as exc:
        parser.exit(1, f'profile_results: {exc}\n')
    print('profile_results: ' + ('updated' if changed else 'unchanged'))


if __name__ == '__main__':
    sys.dont_write_bytecode = True
    main()
